/**
 * Mexican-Spanish equivalence groups used by the "smart" grader.
 *
 * EVERY entry in this file is yours to edit: add a word to `variants` and
 * that phrasing starts being accepted (and, just as importantly, the spelling
 * you used in your CSV starts being accepted too).
 *
 * Rules for editing:
 *  - `canonical` is the single token everything else collapses to, and it must
 *    appear exactly once in the file — that is what the matcher compares.
 *  - `variants` may be single words OR short phrases ("agua de cola").
 *    Multi-word phrases only ever match as a phrase, never as a lone word, so
 *    "cola" on its own is left alone.
 *  - Accents do not matter (the matcher strips them) but writing them keeps
 *    the file readable.
 *  - Register matters: "güey" is accepted for "amigo" because both are what a
 *    Mexican actually says; "formal" would not be.
 */

export interface SynonymGroup {
  /** The single word every variant collapses to. */
  canonical: string;
  variants: string[];
  /** Free-form note shown in Settings → "What smart checking accepts". */
  note?: string;
}

